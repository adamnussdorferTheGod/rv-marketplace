// ─── Lookup helper ──────────────────────────────────────────────────

/** Get a state's tax and fee data by state code (case insensitive). */
export function getStateTaxFees(stateCode: string): StateTaxFees | undefined {
  return STATE_TAX_DATABASE[stateCode.toUpperCase()];
}

// ─── Sorted state list for dropdown UIs ─────────────────────────────

export const STATE_LIST: Array<{ code: string; name: string }> =
  Object.values(STATE_TAX_DATABASE)
    .map(s => ({ code: s.stateCode, name: s.stateName }))
    .sort((a, b) => a.name.localeCompare(b.name));
